#!/usr/bin/env python3
"""Convert the ACT4 ELFs to heliodor hex images and write the gate list.

Usage: gen_suite.py [--list PATH] [--tb] [<SUITE> ...]
  - globs ACT4 ELFs under $ACT_WORK/elfs/**/<SUITE>/*.elf (every suite
    directory when none is named)
  - objcopy -> flat bin -> test/hex/act_<suitelc>_<name>.hex
  - --list writes the gate list read by test/gates/run_act.py and
    test/golden/run_golden.py (one `act_<suitelc>/<name>` entry per ELF)
  - --tb also writes tb/test_act_<suitelc>.veryl, one #[ignore] test per ELF
    on the default core of test_arch_common_harness

Paths come from the environment (set by `source toolchain/env.sh` and the
test/act Makefile):
  ACT_WORK   ACT4 framework work dir holding elfs/  (default: upstream/riscv-arch-test-act/work/heliodor)
  OBJCOPY    riscv elf objcopy                      (default: riscv64-unknown-elf-objcopy on PATH)
"""
import argparse
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))          # <repo>/test/act
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))    # <repo>
ACT_WORK = os.environ.get("ACT_WORK",
                          os.path.join(HERE, "upstream", "riscv-arch-test-act", "work", "heliodor"))
OBJCOPY = os.environ.get("OBJCOPY", "riscv64-unknown-elf-objcopy")
BIN2HEX = os.path.join(REPO, "test", "c", "bin2hex.py")
BINDIR  = os.path.join(HERE, "build", "bin")

# Options of gate-list entries: for every test, by suite and by test. The
# budget covers the slowest suites (element-serial vector divides and
# reductions, H with FP context switches, timer interrupts: up to 1.6M
# cycles); a passing test stops at tohost. Zicntr computes on the
# cycle and instret values, which differ between cores (only the read itself
# is masked), so it is judged by pass/fail; the retire-count mtime keeps its
# `time` reads deterministic.
ALL_OPTS = "budget=2000000"
SUITE_OPTS = {
    "zicntr": "mtime=instret lockstep=0",
    # Their retire streams depend on timing that differs between cores: Zkt
    # keeps cycle counts, InterruptsS takes interrupts at times the core's
    # speed sets, and Sstc compares stimecmp with time.
    "zkt": "lockstep=0",
    "interruptss": "lockstep=0",
    "sstc": "lockstep=0",
}
# These keep HPM counter values, which differ between cores. ExceptionsVls
# runs every vector load and store form up to LMUL 8 element by element
# (3.3M cycles on W2).
TEST_OPTS = {
    "act_sscofpmf/S_inhibit_lo_00": "lockstep=0",
    "act_sscofpmf/U_inhibit_lo_00": "lockstep=0",
    "act_exceptionsvls/rv64": "budget=5000000",
}

# Tests the framework selects but the harness cannot run, with the reason;
# they do not link (no ELF), so this table only records them in the list.
EXCLUDED = {
    "act_sdtrigs/mcontrol6_match_napot_00": "4.3 MiB image, over the 4 MiB harness DRAM",
    "act_sdtrigu/mcontrol6_match_napot_00": "4.3 MiB image, over the 4 MiB harness DRAM",
}

# GL-C compares with the golden model (the old core), which has no Sdtrig and
# no Smstateen/Ssstateen, and known V and H (V = 1) deviations: those tests
# are judged by pass/fail only.
GOLDEN_OFF_SUITE = re.compile(r'^(v[a-z]*\d*|zv[a-z]*\d*|exceptionsv.*|misalignv|h|sdtrig.*|sh.*|s[ms]stateen)$')
GOLDEN_OFF_NAME = re.compile(r'(^|_)(H|HSm|V|VF|VS|VU|vs|vu|sv39x4)(_|$)')
# Single tests the golden model fails (golden_off.list gives the reasons).
GOLDEN_OFF_LIST = os.path.join(HERE, "golden_off.list")

LIST_HEADER = """\
# ACT4 (riscv-arch-test) suites for the new core: the GA (pass/fail) and GL-C
# (final hash against test/golden/act/<suite>.final) gates.
# GENERATED by test/act/gen_suite.py --list from the ELFs of the pinned ACT4
# commit (test/act/Makefile ACT_COMMIT); edit SUITE_OPTS/TEST_OPTS there.
# Images: test/hex/act_<suite>_<name>.hex, gitignored, built by `make -C test/act`
# (see test/act/README.md). Run with test/gates/run_act.py.
"""


def sanitize(s):
    return re.sub(r'[^0-9a-zA-Z]', '_', s)


def suites():
    dirs = glob.glob(f"{ACT_WORK}/elfs/*/*/")
    return sorted({os.path.basename(os.path.normpath(d)) for d in dirs})


def gen(ext, tb):
    extlc = ext.lower()
    elfs = sorted(glob.glob(f"{ACT_WORK}/elfs/**/{ext}/*.elf", recursive=True))
    if not elfs:
        print(f"  [{ext}] no ELFs found under {ACT_WORK}/elfs/**/{ext}/")
        return []
    os.makedirs(BINDIR, exist_ok=True)
    mods = []
    for elf in elfs:
        base = os.path.basename(elf)[:-4]
        m = re.match(rf'^{re.escape(ext)}[-_](.+)$', base)
        short = sanitize(m.group(1)) if m else sanitize(base)
        binf = f"{BINDIR}/{extlc}_{short}.bin"
        hexf = f"{REPO}/test/hex/act_{extlc}_{short}.hex"
        subprocess.run([OBJCOPY, "-O", "binary", elf, binf], check=True)
        subprocess.run(["python3", BIN2HEX, binf, hexf], check=True,
                       stdout=subprocess.DEVNULL)
        mods.append((short, f"test/hex/act_{extlc}_{short}.hex"))
    if tb:
        write_tb(ext, mods)
    print(f"  [{ext}] {len(mods)} tests")
    return [(extlc, short, hexf) for short, hexf in mods]


def write_tb(ext, mods):
    extlc = ext.lower()
    mtime_line = ["        MTIME_EN  : 1'b1,"] if extlc == "zicntr" else []
    out = [
        f"// ACT4 (riscv-arch-test) {ext} compliance suite.",
        "// GENERATED by test/act/gen_suite.py --tb from ACT4 Sail-signed ELFs; do not edit.",
        "// tohost == 1 means the self-check passed. Regenerate via `make -C test/act`.",
        "",
    ]
    for short, hexf in mods:
        mod = f"test_act_{extlc}_{short}"
        out += [
            f"#[test({mod})]",
            "#[ignore]",
            f"module {mod} {{",
            "    inst clk: $tb::clock_gen;",
            "    inst rst: $tb::reset_gen ( clk );",
            "    var pass  : logic    ;",
            "    var fail  : logic    ;",
            "    var tohost: logic<32>;",
            "    inst h: test_arch_common_harness #(",
            f'        HEX_FILE  : "{hexf}",',
            "        TOHOST_IDX: 1024,",
            *mtime_line,
            "    ) (",
            "        clk             ,",
            "        rst             ,",
            "        o_pass  : pass  ,",
            "        o_fail  : fail  ,",
            "        o_tohost: tohost,",
            "    );",
            "    initial {",
            "        rst.assert(clk);",
            "        clk.next  (300000);",
            f'        $display  ("ACT4 {ext}-{short} tohost=%h pass=%b", tohost, pass);',
            f'        $assert   (pass, "ACT4 {ext}-{short} fail");',
            f'        $display  ("ACT4 {ext}-{short} PASS");',
            "        $finish   ();",
            "    }",
            "}",
            "",
        ]
    with open(f"{REPO}/tb/test_act_{extlc}.veryl", "w") as f:
        f.write("\n".join(out))


def golden_off():
    with open(GOLDEN_OFF_LIST) as f:
        return {ln.strip() for ln in f if ln.strip() and not ln.startswith("#")}


def write_list(path, entries):
    off = golden_off()
    lines = [LIST_HEADER]
    lines += [f"# excluded: {k} ({why})" for k, why in sorted(EXCLUDED.items())]
    for extlc, short, hexf in entries:
        key = f"act_{extlc}/{short}"
        if key in EXCLUDED:
            continue
        kv = {}
        for o in " ".join((ALL_OPTS, SUITE_OPTS.get(extlc, ""), TEST_OPTS.get(key, ""))).split():
            k, v = o.split("=", 1)
            kv[k] = v
        opts = " ".join(f"{k}={v}" for k, v in kv.items())
        if "lockstep=" not in opts and (GOLDEN_OFF_SUITE.match(extlc) or GOLDEN_OFF_NAME.search(short) or key in off):
            opts += " lockstep=0"
        lines.append(f"{key} hex={hexf}" + (f" {opts}" if opts else ""))
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  {len(entries)} entries -> {os.path.relpath(path, REPO)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("suites", nargs="*", help="suite directory names (default: all)")
    ap.add_argument("--list", help="write the gate list here")
    ap.add_argument("--tb", action="store_true", help="also write tb/test_act_<suite>.veryl")
    a = ap.parse_args()
    names = a.suites or suites()
    if not names:
        sys.exit(f"gen_suite: no ELFs under {ACT_WORK}/elfs")
    entries = []
    for ext in names:
        entries += gen(ext, a.tb)
    if a.list:
        write_list(a.list, entries)


if __name__ == "__main__":
    main()
