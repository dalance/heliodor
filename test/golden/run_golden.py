#!/usr/bin/env python3
"""Run gate-list tests on the golden model and write the artifacts to master.

    test/golden/run_golden.py [--gen-only] test/gates/<milestone>.list ...

Steps:
  gen   Write tb/golden_runs_<suite>.veryl into the golden worktree, one
        `#[ignore]` test `test_golden_arch_<suite>_<name>` per entry of the
        union of every test/gates/*.list. The union keeps the generated files
        independent of which list is being run. The files must be committed on
        the golden branch before a run (use --allow-dirty to skip that check).
  run   One `veryl test --ignored --test test_golden_arch_<suite>_ --format
        json` per suite with the pinned compiler, then keep the listed tests.
  emit  test/golden/arch/<suite>/<name>.ck.hex and the [arch/<suite>] section
        of test/golden/MANIFEST.

A test is accepted only if tohost == 1, exactly one H line was printed and it
equals the harness summary, the K lines are the consecutive multiples of
2^CK_LOG2, and the retire-contract checker and the FP self-check are clean.
The exit code is non-zero if any listed test was not accepted; accepted tests
are still written.
"""

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

MASTER = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(MASTER / "test" / "gates"))
import gatelist  # noqa: E402

CK_LOG2 = 10
TEST_PREFIX = "test_golden_arch_"
GEN_HEADER = "// Generated by test/golden/run_golden.py from test/gates/*.list. Do not edit.\n"

RE_K = re.compile(r"^K\s+(\d+)\s+([0-9a-fA-F]+)\s*$")
RE_H = re.compile(r"^H\s+(\d+)\s+([0-9a-fA-F]+)\s*$")
RE_SUM = re.compile(r"^golden-arch:\s+(.*)$")


def sh(cmd, cwd, **kw):
    return subprocess.run(cmd, cwd=cwd, check=True, text=True, capture_output=True, **kw).stdout.strip()


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def manifest_header(text: str) -> dict:
    out = {}
    for line in text.splitlines():
        if line.startswith("["):
            break
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def tracer_ver(retire_pkg: Path) -> int:
    m = re.search(r"TRACER_VER\s*:\s*logic<64>\s*=\s*64'h([0-9a-fA-F_]+)", retire_pkg.read_text())
    if not m:
        sys.exit(f"run_golden: TRACER_VER not found in {retire_pkg}")
    return int(m.group(1).replace("_", ""), 16)


def check_pins(golden: Path, veryl: Path, manifest: Path):
    """Refuse to run if the golden worktree no longer matches MANIFEST's pins."""
    hdr = manifest_header(manifest.read_text())
    errs = []
    vc = sh(["git", "rev-parse", "HEAD"], golden / "veryl")
    if vc != hdr.get("veryl_commit"):
        errs.append(f"veryl at {vc}, MANIFEST pins {hdr.get('veryl_commit')}")
    for side in (MASTER, golden):
        s = sha256(side / "src" / "pkg" / "retire_pkg.veryl")
        if s != hdr.get("retire_pkg_sha256"):
            errs.append(f"{side}/src/pkg/retire_pkg.veryl sha256 {s} != MANIFEST")
    tv = tracer_ver(MASTER / "src" / "pkg" / "retire_pkg.veryl")
    if str(tv) != hdr.get("tracer_ver"):
        errs.append(f"TRACER_VER {tv} != MANIFEST tracer_ver {hdr.get('tracer_ver')}")
    branch = sh(["git", "rev-parse", "--abbrev-ref", "HEAD"], golden)
    if branch != hdr.get("golden_branch"):
        errs.append(f"golden worktree on {branch}, MANIFEST names {hdr.get('golden_branch')}")
    if not veryl.is_file():
        errs.append(f"veryl binary {veryl} missing")
    if errs:
        sys.exit("run_golden: stale golden setup:\n  " + "\n  ".join(errs))
    return tv


def gen_module(e) -> str:
    mod = TEST_PREFIX + e.ident
    steps = e.budget // gatelist.EARLY_EXIT_STEP
    vals = [f'"{e.hex}"', str(e.tohost), "1", str(CK_LOG2)]
    w = max(len(v) for v in vals)
    hx, th, ckp, ckl = (v.ljust(w) for v in vals)
    return f"""
#[test({mod})]
#[ignore]
module {mod} {{
    inst clk: $tb::clock_gen;
    inst rst: $tb::reset_gen ( clk );
    var pass  : logic    ;
    var tohost: logic<32>;
    inst h: test_arch_common_harness #(
        HEX_FILE  : {hx},
        TOHOST_IDX: {th},
        CK_PRINT  : {ckp},
        CK_LOG2   : {ckl},
    ) (
        clk             ,
        rst             ,
        o_pass  : pass  ,
        o_fail  : _     ,
        o_tohost: tohost,
    );
    initial {{
        rst.assert(clk);
        for _i in 0..{steps} {{
            clk.next({gatelist.EARLY_EXIT_STEP});
            if tohost != 32'd0 {{
                break;
            }}
        }}
        $display("golden-run {e.key} tohost=%h", tohost);
        $assert(pass, "golden-run {e.key}: tohost != 1");
        $finish();
    }}
}}
"""


def generate(golden: Path) -> list:
    """Write the golden run files for every suite in test/gates/*.list."""
    union = {}
    for lst in sorted((MASTER / "test" / "gates").glob("*.list")):
        for e in gatelist.parse(lst):
            prev = union.get(e.key)
            if prev and prev != e:
                sys.exit(f"run_golden: {e.key} differs between gate lists: {prev} vs {e}")
            union[e.key] = e
    written = []
    for suite, es in sorted(gatelist.by_suite(sorted(union.values(), key=lambda x: x.key)).items()):
        path = golden / "tb" / f"golden_runs_{suite}.veryl"
        text = GEN_HEADER + "".join(gen_module(e) for e in es)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            written.append(path)
    return written


def tree_dirty(golden: Path) -> str:
    return sh(["git", "status", "--porcelain", "--untracked-files=normal", "--", "src", "tb", "Veryl.toml"], golden)


def run_suite(golden: Path, veryl: Path, suite: str, log_dir: Path) -> dict:
    log_dir.mkdir(parents=True, exist_ok=True)
    cmd = [str(veryl), "test", "--ignored", "--test", f"{TEST_PREFIX}{suite}_", "--format", "json"]
    print(f"run_golden: {' '.join(cmd)}", file=sys.stderr, flush=True)
    p = subprocess.run(cmd, cwd=golden, text=True, capture_output=True)
    (log_dir / f"{suite}.json").write_text(p.stdout)
    (log_dir / f"{suite}.err").write_text(p.stderr)
    try:
        rep = json.loads(p.stdout)
    except json.JSONDecodeError:
        sys.exit(f"run_golden: veryl test exited {p.returncode} without a JSON report, see {log_dir}/{suite}.err")
    return {t["name"]: t for t in rep.get("tests", [])}


def judge(t, tv: int) -> tuple:
    """Return (artifact words, summary) or raise ValueError with the reason."""
    if t is None:
        raise ValueError("not run (missing from the veryl report)")
    out = t.get("output", "")
    lines = out.splitlines()
    ks, hs, sums = [], [], []
    for ln in lines:
        if m := RE_K.match(ln):
            ks.append((int(m.group(1)), int(m.group(2), 16)))
        elif m := RE_H.match(ln):
            hs.append((int(m.group(1)), int(m.group(2), 16)))
        elif m := RE_SUM.match(ln):
            sums.append(dict(kv.split("=", 1) for kv in m.group(1).split()))
    if t.get("status") != "pass":
        raise ValueError(f"status {t.get('status')}")
    if any(ln.startswith(("rvfi_tracer: hash mismatch", "golden-chk:", "golden-fpchk:")) for ln in lines):
        raise ValueError("tracer/checker reported a problem")
    if len(hs) != 1 or len(sums) != 1:
        raise ValueError(f"{len(hs)} H lines and {len(sums)} summary lines, expected 1 and 1")
    s = sums[0]
    count, fin = hs[0]
    if int(s["tohost"], 16) != 1:
        raise ValueError(f"tohost={s['tohost']}")
    if set(s["chk"]) - {"0"} or int(s["fpbad"]) != 0:
        raise ValueError(f"chk={s['chk']} fpbad={s['fpbad']}")
    if int(s["records"]) != count or int(s["hash"], 16) != fin:
        raise ValueError("H line disagrees with the harness summary")
    want = [(k << CK_LOG2) for k in range(1, (count >> CK_LOG2) + 1)]
    if [c for c, _ in ks] != want:
        raise ValueError("K lines are not the consecutive checkpoints")
    words = [tv, CK_LOG2, len(ks)] + [h for _, h in ks] + [count, fin]
    return words, {"records": count, "hash": fin, "traps": int(s["traps"]), "instret": int(s["instret"])}


def write_ck(path: Path, words):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(f"{w:016x}\n" for w in words))


def update_manifest(manifest: Path, suite: str, golden_commit: str, rows: dict):
    """Merge rows into the [arch/<suite>] section, keeping untouched rows."""
    text = manifest.read_text()
    tag = f"[arch/{suite}]"
    lines = text.splitlines()
    start = next((i for i, ln in enumerate(lines) if ln.strip() == tag), None)
    old = {}
    if start is not None:
        end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("[")), len(lines))
        prev_commit = None
        for ln in lines[start + 1:end]:
            if ln.startswith("golden_commit"):
                prev_commit = ln.split("=", 1)[1].strip()
            elif ln and not ln.startswith("#") and "=" not in ln:
                old[ln.split()[0]] = ln
        if prev_commit and prev_commit != golden_commit and set(old) - set(rows):
            print(f"run_golden: warning: [arch/{suite}] keeps rows from {prev_commit}", file=sys.stderr)
        while end > start and end - 1 > start and lines[end - 1] == "":
            end -= 1
        del lines[start:end]
        while start < len(lines) and lines[start] == "":
            del lines[start]
        while start > 0 and lines[start - 1] == "":
            start -= 1
            del lines[start]
    else:
        while lines and lines[-1] == "":
            lines.pop()
        start = len(lines)
    merged = dict(old)
    for name, r in rows.items():
        merged[name] = f"{name:<12} {r['sha']} {r['records']:>8} {r['hash']:016x} {r['traps']:>4}"
    sec = [
        "",
        tag,
        f"golden_commit   = {golden_commit}",
        f"test_prefix     = {TEST_PREFIX}{suite}_",
        f"ck_log2         = {CK_LOG2}",
        "mtime_src       = OFF",
        "# ck.hex : test/golden/arch/" + suite + "/<test>.ck.hex, same layout as boot",
        "# <test> <image sha256> <records> <final hash> <traps>",
    ] + [merged[k] for k in sorted(merged)]
    if start < len(lines):
        sec.append("")
    lines[start:start] = sec
    manifest.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("lists", nargs="+", type=Path)
    ap.add_argument("--golden", type=Path, default=MASTER / ".golden")
    ap.add_argument("--veryl", type=Path, default=None)
    ap.add_argument("--gen-only", action="store_true", help="only write tb/golden_runs_*.veryl")
    ap.add_argument("--allow-dirty", action="store_true", help="run with uncommitted golden src/tb changes")
    ap.add_argument("--log-dir", type=Path, default=None)
    a = ap.parse_args()

    golden = a.golden.resolve()
    veryl = (a.veryl or golden / "veryl" / "target" / "release-verylup" / "veryl").resolve()
    manifest = MASTER / "test" / "golden" / "MANIFEST"
    log_dir = a.log_dir or golden / ".build" / "run_golden"

    tv = check_pins(golden, veryl, manifest)
    entries = []
    for lst in a.lists:
        entries += [e for e in gatelist.parse(lst) if e.key not in {x.key for x in entries}]

    for p in generate(golden):
        print(f"run_golden: wrote {p}", file=sys.stderr)
    if a.gen_only:
        return 0
    dirty = tree_dirty(golden)
    if dirty and not a.allow_dirty:
        sys.exit(f"run_golden: golden worktree has uncommitted changes, commit them first:\n{dirty}")
    golden_commit = sh(["git", "rev-parse", "HEAD"], golden) + ("+dirty" if dirty else "")

    failed = []
    for suite, es in gatelist.by_suite(entries).items():
        report = run_suite(golden, veryl, suite, log_dir)
        rows = {}
        for e in es:
            t = report.get(TEST_PREFIX + e.ident)
            try:
                words, s = judge(t, tv)
            except ValueError as ex:
                failed.append(f"{e.key}: {ex}")
                continue
            img = golden / e.hex
            sha = sha256(img)
            mimg = MASTER / e.hex
            if mimg.exists() and sha256(mimg) != sha:
                print(f"run_golden: warning: {e.hex} differs between golden and master", file=sys.stderr)
            write_ck(MASTER / e.ck_file, words)
            rows[e.name] = dict(s, sha=sha)
            print(f"{e.key}: records={s['records']} hash={s['hash']:016x} ck={len(words) - 5}")
        if rows:
            update_manifest(manifest, suite, golden_commit, rows)
    print(f"run_golden: {len(entries) - len(failed)}/{len(entries)} accepted")
    for f in failed:
        print(f"run_golden: FAIL {f}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
