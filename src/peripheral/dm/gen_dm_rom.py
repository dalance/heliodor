#!/usr/bin/env python3
"""Assemble dm_rom.S and write dm_rom_pkg.veryl (the debug ROM words).

    src/peripheral/dm/gen_dm_rom.py

Needs riscv64-unknown-elf-gcc and objcopy on PATH (source toolchain/env.sh).
"""

import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "dm_rom.S"
OUT = HERE / "dm_rom_pkg.veryl"


def main():
    with tempfile.TemporaryDirectory() as d:
        elf = Path(d) / "rom.elf"
        binf = Path(d) / "rom.bin"
        subprocess.run(
            ["riscv64-unknown-elf-gcc", "-march=rv64i_zicsr_zifencei", "-mabi=lp64", "-nostdlib",
             "-nostartfiles", "-Wl,-Ttext=0", "-Wl,-eentry", "-o", str(elf), str(SRC)],
            check=True,
        )
        subprocess.run(["riscv64-unknown-elf-objcopy", "-O", "binary", str(elf), str(binf)], check=True)
        data = binf.read_bytes()
    if len(data) % 8:
        data += b"\x00" * (8 - len(data) % 8)
    words = [struct.unpack_from("<I", data, i)[0] for i in range(0, len(data), 4)]
    body = ",\n".join(f"        32'h{w:08x}" for w in words)
    OUT.write_text(
        "// Generated by src/peripheral/dm/gen_dm_rom.py from dm_rom.S. Do not edit.\n"
        "package dm_rom_pkg {\n"
        f"    const ROM_N: u32 = {len(words)};\n"
        "    const ROM  : bit<32> [ROM_N] = '{\n"
        f"{body}\n"
        "    };\n"
        "}\n"
    )
    print(f"gen_dm_rom: wrote {OUT} ({len(words)} words)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
